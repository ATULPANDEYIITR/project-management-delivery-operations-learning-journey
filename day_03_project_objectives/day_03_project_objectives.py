def validate_project_objective(obj):
    required_fields = [
        "id",
        "statement",
        "baseline",
        "target",
        "kpi",
        "deadline",
        "owner",
        "success_criteria"
    ]

    missing_fields = [
        field for field in required_fields
        if field not in obj
    ]

    if missing_fields:
        return {
            "valid": False,
            "missing_fields": missing_fields
        }

    return {
        "valid": True,
        "missing_fields": []
    }


