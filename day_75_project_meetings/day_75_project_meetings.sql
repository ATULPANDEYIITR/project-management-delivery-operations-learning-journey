-- ============================================================
-- PROJECT MEETING MANAGEMENT SYSTEM
-- PostgreSQL relational workflow implementation
--
-- Includes:
-- Repositories of project work represented by projects,
-- meetings, participants, agenda, decisions, action items,
-- attendance, meeting minutes, notifications, and audit events.
-- ============================================================

CREATE SCHEMA IF NOT EXISTS project_meetings;

SET search_path TO project_meetings, public;

-- ============================================================
-- 1. DOMAIN TABLES
-- ============================================================

CREATE TABLE IF NOT EXISTS projects (
    project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_code VARCHAR(30) NOT NULL UNIQUE,
    project_name VARCHAR(200) NOT NULL,
    project_manager_email VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'on_hold', 'completed', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS participants (
    participant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    department VARCHAR(120),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS meetings (
    meeting_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL
        REFERENCES projects(project_id),
    meeting_code VARCHAR(40) NOT NULL UNIQUE,
    title VARCHAR(250) NOT NULL,
    meeting_type VARCHAR(30) NOT NULL DEFAULT 'project_review'
        CHECK (
            meeting_type IN (
                'kickoff',
                'planning',
                'standup',
                'project_review',
                'risk_review',
                'retrospective',
                'steering_committee'
            )
        ),
    organizer_id BIGINT NOT NULL
        REFERENCES participants(participant_id),
    chairperson_id BIGINT
        REFERENCES participants(participant_id),
    scheduled_start TIMESTAMPTZ NOT NULL,
    duration_minutes INTEGER NOT NULL
        CHECK (duration_minutes BETWEEN 1 AND 1440),
    location VARCHAR(250) NOT NULL,
    meeting_link TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'scheduled'
        CHECK (
            status IN (
                'scheduled',
                'in_progress',
                'completed',
                'cancelled'
            )
        ),
    minutes TEXT,
    cancellation_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT valid_meeting_link
        CHECK (
            meeting_link IS NULL OR
            meeting_link ~ '^https?://'
        ),

    CONSTRAINT valid_cancellation_reason
        CHECK (
            status <> 'cancelled' OR
            cancellation_reason IS NOT NULL
        )
);

CREATE TABLE IF NOT EXISTS meeting_participants (
    meeting_id BIGINT NOT NULL
        REFERENCES meetings(meeting_id) ON DELETE CASCADE,
    participant_id BIGINT NOT NULL
        REFERENCES participants(participant_id),
    role VARCHAR(20) NOT NULL DEFAULT 'member'
        CHECK (
            role IN (
                'organizer',
                'chairperson',
                'member',
                'observer'
            )
        ),
    invitation_status VARCHAR(20) NOT NULL DEFAULT 'invited'
        CHECK (
            invitation_status IN (
                'invited',
                'accepted',
                'declined',
                'tentative'
            )
        ),
    attendance_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (
            attendance_status IN (
                'pending',
                'present',
                'absent',
                'late',
                'excused'
            )
        ),
    joined_at TIMESTAMPTZ,
    PRIMARY KEY (meeting_id, participant_id)
);

CREATE TABLE IF NOT EXISTS agenda_items (
    agenda_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL
        REFERENCES meetings(meeting_id) ON DELETE CASCADE,
    sequence_number INTEGER NOT NULL CHECK (sequence_number > 0),
    title VARCHAR(250) NOT NULL,
    description TEXT,
    owner_id BIGINT NOT NULL,
    planned_minutes INTEGER NOT NULL
        CHECK (planned_minutes > 0),
    priority VARCHAR(15) NOT NULL DEFAULT 'medium'
        CHECK (
            priority IN ('low', 'medium', 'high', 'critical')
        ),
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (
            status IN ('pending', 'in_progress', 'completed', 'deferred')
        ),
    discussion_notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (meeting_id, sequence_number),

    FOREIGN KEY (meeting_id, owner_id)
        REFERENCES meeting_participants(meeting_id, participant_id)
);

CREATE TABLE IF NOT EXISTS decisions (
    decision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL
        REFERENCES meetings(meeting_id) ON DELETE CASCADE,
    decision_number INTEGER NOT NULL,
    description TEXT NOT NULL,
    rationale TEXT,
    recorded_by BIGINT NOT NULL,
    decision_status VARCHAR(20) NOT NULL DEFAULT 'approved'
        CHECK (
            decision_status IN (
                'approved',
                'rejected',
                'deferred',
                'under_review'
            )
        ),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    UNIQUE (meeting_id, decision_number),

    FOREIGN KEY (meeting_id, recorded_by)
        REFERENCES meeting_participants(meeting_id, participant_id)
);

CREATE TABLE IF NOT EXISTS action_items (
    action_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL
        REFERENCES meetings(meeting_id),
    agenda_item_id BIGINT
        REFERENCES agenda_items(agenda_item_id),
    action_code VARCHAR(40) NOT NULL UNIQUE,
    description TEXT NOT NULL,
    assignee_id BIGINT NOT NULL,
    assigned_by BIGINT NOT NULL,
    priority VARCHAR(15) NOT NULL DEFAULT 'medium'
        CHECK (
            priority IN ('low', 'medium', 'high', 'critical')
        ),
    status VARCHAR(20) NOT NULL DEFAULT 'open'
        CHECK (
            status IN (
                'open',
                'in_progress',
                'blocked',
                'completed',
                'cancelled'
            )
        ),
    due_date TIMESTAMPTZ NOT NULL,
    completed_at TIMESTAMPTZ,
    completion_notes TEXT,
    blocker_description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    FOREIGN KEY (meeting_id, assignee_id)
        REFERENCES meeting_participants(meeting_id, participant_id),

    FOREIGN KEY (meeting_id, assigned_by)
        REFERENCES meeting_participants(meeting_id, participant_id),

    CONSTRAINT completed_action_evidence
        CHECK (
            status <> 'completed' OR
            (
                completed_at IS NOT NULL AND
                completion_notes IS NOT NULL
            )
        ),

    CONSTRAINT blocked_action_reason
        CHECK (
            status <> 'blocked' OR
            blocker_description IS NOT NULL
        )
);

CREATE TABLE IF NOT EXISTS meeting_documents (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT NOT NULL
        REFERENCES meetings(meeting_id) ON DELETE CASCADE,
    document_name VARCHAR(250) NOT NULL,
    document_type VARCHAR(30) NOT NULL
        CHECK (
            document_type IN (
                'agenda',
                'minutes',
                'presentation',
                'report',
                'attachment'
            )
        ),
    storage_reference TEXT NOT NULL,
    uploaded_by BIGINT NOT NULL
        REFERENCES participants(participant_id),
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

