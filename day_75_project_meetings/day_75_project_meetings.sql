-- 15. CTE-BASED PROJECT ACTION ANALYSIS
-- ============================================================

WITH project_actions AS (
    SELECT
        p.project_id,
        p.project_name,
        a.action_id,
        a.status,
        a.due_date,
        a.priority
    FROM projects p
    JOIN meetings m
        ON m.project_id = p.project_id
    JOIN action_items a
        ON a.meeting_id = m.meeting_id
),
action_metrics AS (
    SELECT
        project_id,
        project_name,
        COUNT(*) AS total_actions,
        COUNT(*) FILTER (
            WHERE status = 'completed'
        ) AS completed_actions,
        COUNT(*) FILTER (
            WHERE status <> 'completed'
              AND status <> 'cancelled'
              AND due_date < CURRENT_TIMESTAMP
        ) AS overdue_actions
    FROM project_actions
    GROUP BY project_id, project_name
)
SELECT
    project_name,
    total_actions,
    completed_actions,
    overdue_actions,
    ROUND(
        100.0 * completed_actions /
        NULLIF(total_actions, 0),
        2
    ) AS completion_percentage
FROM action_metrics
ORDER BY overdue_actions DESC;

