CREATE OR REPLACE FUNCTION validate_meeting_participant()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    meeting_status VARCHAR(20);
    participant_active BOOLEAN;
BEGIN
    SELECT status
    INTO meeting_status
    FROM meetings
    WHERE meeting_id = NEW.meeting_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Meeting does not exist.';
    END IF;

    IF meeting_status <> 'scheduled' THEN
        RAISE EXCEPTION
            'Participants cannot be added after meeting starts.';
    END IF;

    SELECT is_active
    INTO participant_active
    FROM participants
    WHERE participant_id = NEW.participant_id;

    IF NOT FOUND OR NOT participant_active THEN
        RAISE EXCEPTION 'Participant is inactive or unavailable.';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_meeting_participant
    ON meeting_participants;

CREATE TRIGGER trg_validate_meeting_participant
BEFORE INSERT ON meeting_participants
FOR EACH ROW
EXECUTE FUNCTION validate_meeting_participant();


CREATE OR REPLACE FUNCTION validate_meeting_lifecycle()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    agenda_count INTEGER;
    participant_count INTEGER;
BEGIN
    IF OLD.status = 'completed' OR OLD.status = 'cancelled' THEN
        IF NEW.status <> OLD.status THEN
            RAISE EXCEPTION
                'Terminal meeting status cannot be changed.';
        END IF;
    END IF;

    IF OLD.status = 'scheduled'
       AND NEW.status = 'in_progress' THEN

        SELECT COUNT(*)
        INTO agenda_count
        FROM agenda_items
        WHERE meeting_id = NEW.meeting_id;

        IF agenda_count = 0 THEN
            RAISE EXCEPTION
                'At least one agenda item is required.';
        END IF;

        SELECT COUNT(*)
        INTO participant_count
        FROM meeting_participants
        WHERE meeting_id = NEW.meeting_id;

        IF participant_count < 1 THEN
            RAISE EXCEPTION
                'Meeting requires participants.';
        END IF;
    END IF;

    IF OLD.status = 'in_progress'
       AND NEW.status = 'completed'
       AND NEW.minutes IS NULL THEN
        RAISE EXCEPTION 'Meeting minutes are required.';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_meeting_lifecycle
    ON meetings;

CREATE TRIGGER trg_meeting_lifecycle
BEFORE UPDATE OF status ON meetings
FOR EACH ROW
EXECUTE FUNCTION validate_meeting_lifecycle();


CREATE OR REPLACE FUNCTION validate_action_transition()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status = 'completed' AND NEW.status <> 'completed' THEN
        RAISE EXCEPTION 'Completed action cannot be reopened.';
    END IF;

    IF NEW.status = 'completed' THEN
        IF NEW.completion_notes IS NULL
           OR NEW.completed_at IS NULL THEN
            RAISE EXCEPTION
                'Completion requires evidence and completion time.';
        END IF;
    END IF;

    IF NEW.status = 'blocked'
       AND NEW.blocker_description IS NULL THEN
        RAISE EXCEPTION 'Blocked action requires a reason.';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_action_transition
    ON action_items;

CREATE TRIGGER trg_action_transition
BEFORE UPDATE ON action_items
FOR EACH ROW
EXECUTE FUNCTION validate_action_transition();


CREATE OR REPLACE FUNCTION validate_action_meeting_state()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    current_status VARCHAR(20);
BEGIN
    SELECT status
    INTO current_status
    FROM meetings
    WHERE meeting_id = NEW.meeting_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Meeting does not exist.';
    END IF;

    IF current_status <> 'in_progress' THEN
        RAISE EXCEPTION
            'New actions must be assigned during an active meeting.';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_action_meeting_state
    ON action_items;

CREATE TRIGGER trg_action_meeting_state
BEFORE INSERT ON action_items
FOR EACH ROW
EXECUTE FUNCTION validate_action_meeting_state();

