-- 7. POLICY EVALUATION FUNCTION
-- ============================================================

CREATE OR REPLACE FUNCTION evaluate_meeting(
    p_meeting_id BIGINT,
    p_policy_id BIGINT
)
RETURNS TABLE (
    eligible BOOLEAN,
    agenda_count BIGINT,
    participant_count BIGINT,
    policy_violations TEXT[]
)
LANGUAGE plpgsql
AS $$
DECLARE
    meeting_record RECORD;
    policy_record RECORD;
    agenda_total BIGINT;
    participant_total BIGINT;
    violations TEXT[] := ARRAY[]::TEXT[];
BEGIN
    SELECT *
    INTO meeting_record
    FROM meetings
    WHERE meeting_id = p_meeting_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Meeting not found: %', p_meeting_id;
    END IF;

    SELECT *
    INTO policy_record
    FROM meeting_policies
    WHERE policy_id = p_policy_id
      AND enabled = TRUE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Active meeting policy not found.';
    END IF;

    SELECT COUNT(*)
    INTO agenda_total
    FROM agenda_items
    WHERE meeting_id = p_meeting_id;

    SELECT COUNT(*)
    INTO participant_total
    FROM meeting_participants
    WHERE meeting_id = p_meeting_id;

    IF meeting_record.duration_minutes >
       policy_record.maximum_duration_minutes THEN
        violations := array_append(
            violations,
            'Maximum duration exceeded'
        );
    END IF;

    IF agenda_total < policy_record.minimum_agenda_items THEN
        violations := array_append(
            violations,
            'Minimum agenda requirement not satisfied'
        );
    END IF;

    IF participant_total > policy_record.maximum_participants THEN
        violations := array_append(
            violations,
            'Maximum participant count exceeded'
        );
    END IF;

    RETURN QUERY SELECT
        cardinality(violations) = 0,
        agenda_total,
        participant_total,
        violations;
END;
$$;

