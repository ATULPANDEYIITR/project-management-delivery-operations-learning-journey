CREATE TABLE IF NOT EXISTS meeting_policies (
    policy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy_name VARCHAR(150) NOT NULL UNIQUE,
    maximum_duration_minutes INTEGER NOT NULL
        CHECK (maximum_duration_minutes > 0),
    minimum_agenda_items INTEGER NOT NULL DEFAULT 1
        CHECK (minimum_agenda_items >= 0),
    maximum_participants INTEGER NOT NULL DEFAULT 50
        CHECK (maximum_participants > 0),
    minutes_required BOOLEAN NOT NULL DEFAULT TRUE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS meeting_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id BIGINT
        REFERENCES meetings(meeting_id) ON DELETE SET NULL,
    action_type VARCHAR(60) NOT NULL,
    actor_id BIGINT
        REFERENCES participants(participant_id) ON DELETE SET NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

