CREATE OR REPLACE FUNCTION record_meeting_audit()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO meeting_audit (
        meeting_id,
        action_type,
        details
    )
    VALUES (
        NEW.meeting_id,
        CASE
            WHEN TG_OP = 'INSERT' THEN 'meeting_created'
            WHEN OLD.status IS DISTINCT FROM NEW.status
                THEN 'meeting_status_changed'
            ELSE 'meeting_updated'
        END,
        jsonb_build_object(
            'old_status',
            CASE WHEN TG_OP = 'UPDATE' THEN OLD.status ELSE NULL END,
            'new_status', NEW.status,
            'title', NEW.title
        )
    );

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_meeting_audit
    ON meetings;

CREATE TRIGGER trg_meeting_audit
AFTER INSERT OR UPDATE ON meetings
FOR EACH ROW
EXECUTE FUNCTION record_meeting_audit();

