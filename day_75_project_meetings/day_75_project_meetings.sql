CREATE OR REPLACE VIEW meeting_overview AS
SELECT
    m.meeting_id,
    m.meeting_code,
    m.title,
    p.project_code,
    p.project_name,
    organizer.full_name AS organizer_name,
    m.scheduled_start,
    m.duration_minutes,
    m.status,
    COUNT(DISTINCT mp.participant_id) AS participant_count,
    COUNT(DISTINCT ai.agenda_item_id) AS agenda_count,
    COUNT(DISTINCT d.decision_id) AS decision_count,
    COUNT(DISTINCT a.action_id) AS action_count
FROM meetings m
JOIN projects p
    ON p.project_id = m.project_id
JOIN participants organizer
    ON organizer.participant_id = m.organizer_id
LEFT JOIN meeting_participants mp
    ON mp.meeting_id = m.meeting_id
LEFT JOIN agenda_items ai
    ON ai.meeting_id = m.meeting_id
LEFT JOIN decisions d
    ON d.meeting_id = m.meeting_id
LEFT JOIN action_items a
    ON a.meeting_id = m.meeting_id
GROUP BY
    m.meeting_id,
    m.meeting_code,
    m.title,
    p.project_code,
    p.project_name,
    organizer.full_name,
    m.scheduled_start,
    m.duration_minutes,
    m.status;


CREATE OR REPLACE VIEW action_tracking AS
SELECT
    a.action_id,
    a.action_code,
    a.description,
    a.priority,
    a.status,
    a.due_date,
    a.completed_at,
    p.full_name AS assignee,
    m.meeting_code,
    m.title AS meeting_title,
    pr.project_name,
    CASE
        WHEN a.status = 'completed' THEN 'Completed'
        WHEN a.due_date < CURRENT_TIMESTAMP THEN 'Overdue'
        WHEN a.status = 'blocked' THEN 'Blocked'
        ELSE 'Within Deadline'
    END AS delivery_state
FROM action_items a
JOIN participants p
    ON p.participant_id = a.assignee_id
JOIN meetings m
    ON m.meeting_id = a.meeting_id
JOIN projects pr
    ON pr.project_id = m.project_id;


CREATE OR REPLACE VIEW project_meeting_performance AS
SELECT
    p.project_id,
    p.project_code,
    p.project_name,
    COUNT(DISTINCT m.meeting_id) AS total_meetings,
    COUNT(DISTINCT m.meeting_id)
        FILTER (WHERE m.status = 'completed') AS completed_meetings,
    COUNT(DISTINCT m.meeting_id)
        FILTER (WHERE m.status = 'cancelled') AS cancelled_meetings,
    COUNT(DISTINCT d.decision_id) AS decisions_recorded,
    COUNT(DISTINCT a.action_id) AS total_actions,
    COUNT(DISTINCT a.action_id)
        FILTER (WHERE a.status = 'completed') AS completed_actions,
    COUNT(DISTINCT a.action_id)
        FILTER (
            WHERE a.status <> 'completed'
              AND a.status <> 'cancelled'
              AND a.due_date < CURRENT_TIMESTAMP
        ) AS overdue_actions
FROM projects p
LEFT JOIN meetings m
    ON m.project_id = p.project_id
LEFT JOIN decisions d
    ON d.meeting_id = m.meeting_id
LEFT JOIN action_items a
    ON a.meeting_id = m.meeting_id
GROUP BY p.project_id, p.project_code, p.project_name;

