-- ============================================================

CREATE OR REPLACE PROCEDURE start_meeting(
    p_meeting_id BIGINT,
    p_policy_id BIGINT
)
LANGUAGE plpgsql
AS $$
DECLARE
    result_record RECORD;
BEGIN
    SELECT *
    INTO result_record
    FROM evaluate_meeting(p_meeting_id, p_policy_id);

    IF NOT result_record.eligible THEN
        RAISE EXCEPTION
            'Meeting is not eligible: %',
            result_record.policy_violations;
    END IF;

    UPDATE meetings
    SET status = 'in_progress'
    WHERE meeting_id = p_meeting_id
      AND status = 'scheduled';

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Meeting is not in scheduled state.';
    END IF;
END;
$$;


CREATE OR REPLACE PROCEDURE complete_action(
    p_action_id BIGINT,
    p_completion_notes TEXT
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_completion_notes IS NULL
       OR length(trim(p_completion_notes)) = 0 THEN
        RAISE EXCEPTION 'Completion notes are mandatory.';
    END IF;

    UPDATE action_items
    SET
        status = 'completed',
        completion_notes = trim(p_completion_notes),
        completed_at = CURRENT_TIMESTAMP
    WHERE action_id = p_action_id
      AND status <> 'completed';

    IF NOT FOUND THEN
        RAISE EXCEPTION
            'Action does not exist or is already completed.';
    END IF;
END;
$$;

