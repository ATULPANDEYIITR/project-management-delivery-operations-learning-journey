-- CTE-based eligibility evaluation for each project.
WITH validation AS (
    SELECT
        project_id,
        COUNT(*) AS total_tasks,
        COUNT(*) FILTER (WHERE NOT is_valid) AS invalid_tasks,
        BOOL_AND(is_valid) AS all_tasks_valid
    FROM raci.v_matrix_validation
    GROUP BY project_id
)
SELECT
    p.project_id,
    p.project_code,
    p.status,
    COALESCE(v.total_tasks, 0) AS total_tasks,
    COALESCE(v.invalid_tasks, 0) AS invalid_tasks,
    (
        p.status = 'DRAFT'
        AND COALESCE(v.total_tasks, 0) > 0
        AND COALESCE(v.all_tasks_valid, FALSE)
    ) AS eligible_for_publication
FROM raci.projects AS p
LEFT JOIN validation AS v
       ON v.project_id = p.project_id
ORDER BY p.project_id;

