-- Demonstrate that the partial unique index rejects a second A.
-- The exception block rolls back only the failed statement.
DO $$
BEGIN
    UPDATE raci.raci_assignments
       SET responsibility = 'A'
     WHERE project_id = 200
       AND task_id = 20001
       AND role_id = 2003;

    RAISE EXCEPTION 'Expected duplicate-accountability constraint was not raised';
EXCEPTION
    WHEN unique_violation THEN
        RAISE NOTICE 'Second A rejected by uq_one_accountable_per_task.';
END;
$$;

