-- RACI Matrix: project roles, work items, assignments, validation, and publication.
-- Designed for PostgreSQL. Run the complete script in a database where the
-- executing user has permission to create schemas, tables, functions, and triggers.

BEGIN;

DROP SCHEMA IF EXISTS raci CASCADE;
CREATE SCHEMA raci;

CREATE TYPE raci.responsibility_code AS ENUM ('R', 'A', 'C', 'I');

CREATE TABLE raci.projects (
    project_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_code     VARCHAR(40) NOT NULL UNIQUE,
    project_name     VARCHAR(200) NOT NULL,
    status           VARCHAR(12) NOT NULL DEFAULT 'DRAFT'
                     CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED')),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    published_at     TIMESTAMPTZ,
    CHECK (
        (status = 'ACTIVE' AND published_at IS NOT NULL)
        OR status <> 'ACTIVE'
    )
);

CREATE TABLE raci.project_roles (
    role_id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id               BIGINT NOT NULL
                             REFERENCES raci.projects(project_id)
                             ON DELETE CASCADE,
    role_code                VARCHAR(50) NOT NULL,
    role_name                VARCHAR(150) NOT NULL,
    department               VARCHAR(150) NOT NULL,
    max_responsible_tasks    INTEGER,
    UNIQUE (project_id, role_code),
    UNIQUE (project_id, role_id),
    CHECK (length(trim(role_code)) > 0),
    CHECK (length(trim(role_name)) > 0),
    CHECK (
        max_responsible_tasks IS NULL
        OR max_responsible_tasks >= 0
    )
);

CREATE TABLE raci.work_items (
    task_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id          BIGINT NOT NULL
                        REFERENCES raci.projects(project_id)
                        ON DELETE CASCADE,
    task_code           VARCHAR(40) NOT NULL,
    task_name           VARCHAR(200) NOT NULL,
    security_sensitive  BOOLEAN NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (project_id, task_id),
    UNIQUE (project_id, task_code),
    CHECK (length(trim(task_code)) > 0),
    CHECK (length(trim(task_name)) > 0)
);

CREATE TABLE raci.raci_assignments (
    assignment_id   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    project_id      BIGINT NOT NULL,
    task_id         BIGINT NOT NULL,
    role_id         BIGINT NOT NULL,
    responsibility  raci.responsibility_code NOT NULL,
    assigned_by     TEXT NOT NULL DEFAULT current_user,
    assigned_at     TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),

    CONSTRAINT uq_assignment_task_role
        UNIQUE (project_id, task_id, role_id),

    CONSTRAINT fk_assignment_task
        FOREIGN KEY (project_id, task_id)
        REFERENCES raci.work_items(project_id, task_id)
        ON DELETE CASCADE,

    CONSTRAINT fk_assignment_role
        FOREIGN KEY (project_id, role_id)
        REFERENCES raci.project_roles(project_id, role_id)
        ON DELETE CASCADE
);

-- A partial unique index enforces at most one A per task.
-- The publication function enforces that every task has exactly one A.
CREATE UNIQUE INDEX uq_one_accountable_per_task
    ON raci.raci_assignments(project_id, task_id)
    WHERE responsibility = 'A';

CREATE INDEX idx_assignment_task
    ON raci.raci_assignments(project_id, task_id);

CREATE INDEX idx_assignment_role_responsibility
    ON raci.raci_assignments(project_id, role_id, responsibility, task_id);

CREATE INDEX idx_work_items_project
    ON raci.work_items(project_id, task_code);

CREATE TABLE raci.assignment_audit (
    audit_id       BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    project_id     BIGINT NOT NULL,
    action         VARCHAR(10) NOT NULL
                   CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    old_data       JSONB,
    new_data       JSONB,
    actor          TEXT NOT NULL DEFAULT current_user,
    occurred_at    TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX idx_assignment_audit_project_time
    ON raci.assignment_audit(project_id, occurred_at DESC);

-- Active matrices cannot have their assignments modified.
-- FOR SHARE serializes assignment changes against publication, which locks
-- the same project row FOR UPDATE.
CREATE OR REPLACE FUNCTION raci.guard_assignment_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_project_id BIGINT;
    v_status     VARCHAR(12);
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.project_id <> OLD.project_id
           OR NEW.task_id <> OLD.task_id
           OR NEW.role_id <> OLD.role_id THEN
            RAISE EXCEPTION
                'Assignment ownership keys cannot be changed; delete and recreate the assignment';
        END IF;
        v_project_id := NEW.project_id;
    ELSIF TG_OP = 'INSERT' THEN
        v_project_id := NEW.project_id;
    ELSE
        v_project_id := OLD.project_id;
    END IF;

    SELECT status
      INTO v_status
      FROM raci.projects
     WHERE project_id = v_project_id
     FOR SHARE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Project % does not exist', v_project_id;
    END IF;

    IF v_status = 'ACTIVE' THEN
        RAISE EXCEPTION
            'Assignments cannot be modified after project % is published',
            v_project_id;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_guard_assignment_mutation
BEFORE INSERT OR UPDATE OR DELETE
ON raci.raci_assignments
FOR EACH ROW
EXECUTE FUNCTION raci.guard_assignment_mutation();

-- Work-item definitions are also frozen after publication.
CREATE OR REPLACE FUNCTION raci.guard_work_item_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_project_id BIGINT;
    v_status     VARCHAR(12);
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.project_id <> OLD.project_id THEN
            RAISE EXCEPTION 'A work item cannot be moved between projects';
        END IF;
        v_project_id := NEW.project_id;
    ELSIF TG_OP = 'INSERT' THEN
        v_project_id := NEW.project_id;
    ELSE
        v_project_id := OLD.project_id;
    END IF;

    SELECT status
      INTO v_status
      FROM raci.projects
     WHERE project_id = v_project_id
     FOR SHARE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Project % does not exist', v_project_id;
    END IF;

    IF v_status = 'ACTIVE' THEN
        RAISE EXCEPTION
            'Work items cannot be modified after project % is published',
            v_project_id;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_guard_work_item_mutation
BEFORE INSERT OR UPDATE OR DELETE
ON raci.work_items
FOR EACH ROW
EXECUTE FUNCTION raci.guard_work_item_mutation();

-- Assignment changes are recorded independently from the current matrix.
CREATE OR REPLACE FUNCTION raci.audit_assignment_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_project_id BIGINT;
    v_old_data   JSONB;
    v_new_data   JSONB;
BEGIN
    IF TG_OP = 'INSERT' THEN
        v_project_id := NEW.project_id;
        v_new_data := to_jsonb(NEW);
    ELSIF TG_OP = 'UPDATE' THEN
        v_project_id := NEW.project_id;
        v_old_data := to_jsonb(OLD);
        v_new_data := to_jsonb(NEW);
    ELSE
        v_project_id := OLD.project_id;
        v_old_data := to_jsonb(OLD);
    END IF;

    INSERT INTO raci.assignment_audit (
        project_id,
        action,
        old_data,
        new_data
    )
    VALUES (
        v_project_id,
        TG_OP,
        v_old_data,
        v_new_data
    );

    RETURN NULL;
END;
$$;

CREATE TRIGGER trg_audit_assignment_change
AFTER INSERT OR UPDATE OR DELETE
ON raci.raci_assignments
FOR EACH ROW
EXECUTE FUNCTION raci.audit_assignment_change();

-- One row per task, with counts used by validation and reporting.
CREATE OR REPLACE VIEW raci.v_matrix_validation AS
SELECT
    wi.project_id,
    wi.task_id,
    wi.task_code,
    wi.task_name,
    wi.security_sensitive,
    COUNT(a.assignment_id)
        FILTER (WHERE a.responsibility = 'A') AS accountable_count,
    COUNT(a.assignment_id)
        FILTER (WHERE a.responsibility = 'R') AS responsible_count,
    COUNT(a.assignment_id)
        FILTER (
            WHERE pr.role_code = 'SECURITY_OFFICER'
              AND a.responsibility = 'C'
        ) AS security_consult_count,
    (
        COUNT(a.assignment_id)
            FILTER (WHERE a.responsibility = 'A') = 1
        AND
        COUNT(a.assignment_id)
            FILTER (WHERE a.responsibility = 'R') >= 1
        AND
        (
            NOT wi.security_sensitive
            OR COUNT(a.assignment_id)
                FILTER (
                    WHERE pr.role_code = 'SECURITY_OFFICER'
                      AND a.responsibility = 'C'
                ) >= 1
        )
    ) AS is_valid
FROM raci.work_items AS wi
LEFT JOIN raci.raci_assignments AS a
       ON a.project_id = wi.project_id
      AND a.task_id = wi.task_id
LEFT JOIN raci.project_roles AS pr
       ON pr.project_id = a.project_id
      AND pr.role_id = a.role_id
GROUP BY
    wi.project_id,
    wi.task_id,
    wi.task_code,
    wi.task_name,
    wi.security_sensitive;

-- A readable representation of each task's RACI assignments.
CREATE OR REPLACE VIEW raci.v_task_matrix AS
SELECT
    wi.project_id,
    wi.task_code,
    wi.task_name,
    string_agg(
        pr.role_code || '=' || a.responsibility::TEXT,
        ', ' ORDER BY pr.role_code
    ) AS assignments
FROM raci.work_items AS wi
LEFT JOIN raci.raci_assignments AS a
       ON a.project_id = wi.project_id
      AND a.task_id = wi.task_id
LEFT JOIN raci.project_roles AS pr
       ON pr.project_id = a.project_id
      AND pr.role_id = a.role_id
GROUP BY
    wi.project_id,
    wi.task_id,
    wi.task_code,
    wi.task_name;

-- Workload measures R assignments by distinct work item.
-- Capacity overruns are reported as warnings rather than automatic blockers.
CREATE OR REPLACE VIEW raci.v_role_workload AS
SELECT
    pr.project_id,
    pr.role_id,
    pr.role_code,
    pr.role_name,
    pr.max_responsible_tasks,
    COUNT(DISTINCT a.task_id)
        FILTER (WHERE a.responsibility = 'R') AS responsible_task_count,
    (
        pr.max_responsible_tasks IS NOT NULL
        AND COUNT(DISTINCT a.task_id)
            FILTER (WHERE a.responsibility = 'R')
            > pr.max_responsible_tasks
    ) AS over_capacity
FROM raci.project_roles AS pr
LEFT JOIN raci.raci_assignments AS a
       ON a.project_id = pr.project_id
      AND a.role_id = pr.role_id
GROUP BY
    pr.project_id,
    pr.role_id,
    pr.role_code,
    pr.role_name,
    pr.max_responsible_tasks;

-- Publication validates every work item while holding a project-level lock.
-- Assignment triggers use FOR SHARE, preventing concurrent changes from
-- passing the DRAFT check while publication is changing the project status.
CREATE OR REPLACE FUNCTION raci.publish_matrix(p_project_id BIGINT)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    v_status          VARCHAR(12);
    v_task_count      BIGINT;
    v_invalid_count   BIGINT;
    v_overload_count  BIGINT;
BEGIN
    SELECT status
      INTO v_status
      FROM raci.projects
     WHERE project_id = p_project_id
     FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Project % does not exist', p_project_id;
    END IF;

    IF v_status <> 'DRAFT' THEN
        RAISE EXCEPTION
            'Only DRAFT projects can be published; current status is %',
            v_status;
    END IF;

    SELECT COUNT(*)
      INTO v_task_count
      FROM raci.work_items
     WHERE project_id = p_project_id;

    IF v_task_count = 0 THEN
        RAISE EXCEPTION 'Project % has no work items', p_project_id;
    END IF;

    SELECT COUNT(*)
      INTO v_invalid_count
      FROM raci.v_matrix_validation
     WHERE project_id = p_project_id
       AND NOT is_valid;

    IF v_invalid_count > 0 THEN
        RAISE EXCEPTION
            'Publication blocked: project % has % invalid work item(s)',
            p_project_id,
            v_invalid_count;
    END IF;

    SELECT COUNT(*)
      INTO v_overload_count
      FROM raci.v_role_workload
     WHERE project_id = p_project_id
       AND over_capacity;

    IF v_overload_count > 0 THEN
        RAISE WARNING
            'Project % has % role(s) above their Responsible-task capacity',
            p_project_id,
            v_overload_count;
    END IF;

    UPDATE raci.projects
       SET status = 'ACTIVE',
           published_at = clock_timestamp()
     WHERE project_id = p_project_id;
END;
$$;

